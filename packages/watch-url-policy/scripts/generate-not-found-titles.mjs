import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const packageDirectory = join(dirname(fileURLToPath(import.meta.url)), "..")
const messagesDirectory = join(packageDirectory, "../../apps/web/messages")
const outputPath = join(packageDirectory, "src/not-found-titles.ts")
const checkOnly = process.argv.includes("--check")
const unknownArguments = process.argv
  .slice(2)
  .filter((value) => value !== "--check")

if (unknownArguments.length > 0) {
  throw new Error(`Unknown arguments: ${unknownArguments.join(", ")}`)
}

const messageFiles = readdirSync(messagesDirectory)
  .filter((file) => file.endsWith(".json"))
  .sort()
const titles = messageFiles.map((file) => {
  const messages = JSON.parse(
    readFileSync(join(messagesDirectory, file), "utf8"),
  )
  const title = messages.WatchNotFound?.metadataTitle
  if (typeof title !== "string" || title.trim() === "") {
    throw new Error(`${file} is missing WatchNotFound.metadataTitle`)
  }
  return title
})
const uniqueTitles = [...new Set(titles)].sort()

const generated = `// This file is generated by \`pnpm --filter @forge/watch-url-policy generate:not-found-titles\`.
// Do not edit it by hand. Web's parity test prevents the runtime GA4 filter
// catalog from drifting from apps/web/messages/*.

export const WATCH_NOT_FOUND_METADATA_TITLE_SOURCE_CATALOG_COUNT = ${messageFiles.length}

export const WATCH_NOT_FOUND_METADATA_TITLES = [
${uniqueTitles.map((title) => `  ${JSON.stringify(title)},`).join("\n")}
] as const
`

if (checkOnly) {
  let current = ""
  try {
    current = readFileSync(outputPath, "utf8")
  } catch {
    // The mismatch error below covers a missing generated artifact too.
  }
  if (current !== generated) {
    console.error(
      "Watch not-found title catalog is stale. Run: pnpm --filter @forge/watch-url-policy generate:not-found-titles",
    )
    process.exitCode = 1
  }
} else {
  writeFileSync(outputPath, generated)
}
