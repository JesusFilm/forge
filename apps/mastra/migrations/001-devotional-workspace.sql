create table if not exists devotional_workspace.catalog_generations (
  id bigint generated by default as identity primary key,
  status text not null check (status in ('staging', 'committed', 'failed', 'retired')),
  inventory_digest text not null,
  file_count integer not null check (file_count >= 0),
  decoded_bytes bigint not null check (decoded_bytes >= 0),
  vector_index_name text not null unique,
  failure_reason text,
  created_at timestamptz not null default now(),
  committed_at timestamptz,
  retired_at timestamptz
);

create table if not exists devotional_workspace.catalog_entries (
  generation_id bigint not null references devotional_workspace.catalog_generations(id) on delete cascade,
  path text not null,
  category text not null,
  digest text not null check (digest ~ '^[0-9a-f]{64}$'),
  byte_size integer not null check (byte_size >= 0),
  modified_at timestamptz,
  etag text,
  content text not null,
  metadata jsonb not null default '{}'::jsonb,
  primary key (generation_id, path)
);

create index if not exists catalog_entries_category_idx
  on devotional_workspace.catalog_entries (generation_id, category, path);

create table if not exists devotional_workspace.catalog_head (
  singleton boolean primary key default true check (singleton),
  generation_id bigint not null references devotional_workspace.catalog_generations(id),
  updated_at timestamptz not null default now()
);

create table if not exists devotional_workspace.reconciliation_lease (
  singleton boolean primary key default true check (singleton),
  holder_id text not null,
  fencing_token bigint not null check (fencing_token > 0),
  expires_at timestamptz not null,
  updated_at timestamptz not null default now()
);

create table if not exists devotional_workspace.workflow_attempts (
  id text primary key,
  parent_run_id text not null,
  idempotency_key text not null,
  request_hash text not null check (request_hash ~ '^[0-9a-f]{64}$'),
  attempt_number integer not null check (attempt_number > 0),
  catalog_generation bigint references devotional_workspace.catalog_generations(id),
  run_id text,
  selected_sources jsonb not null default '[]'::jsonb
    check (jsonb_typeof(selected_sources) = 'array'),
  provisioning_state text not null check (
    provisioning_state in ('provisioning', 'ready', 'failed')
  ),
  failure_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (parent_run_id, idempotency_key),
  unique (parent_run_id, attempt_number)
);

create table if not exists devotional_workspace.clip_state (
