create schema if not exists devotional_workspace;
create extension if not exists vector;

create table if not exists devotional_workspace.schema_migrations (
  version integer primary key check (version > 0),
  name text not null,
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  applied_at timestamptz not null default now()
);

create table if not exists devotional_workspace.filesystem_mutation_audit (
  sequence_id bigint generated always as identity primary key,
  id text not null unique,
  occurred_at timestamptz not null,
  actor_id text not null,
  request_id text not null,
  action text not null check (
    action in ('write', 'append', 'delete', 'copy', 'move', 'mkdir', 'rmdir')
  ),
  path text not null,
  target_path text,
  pre_digest text check (pre_digest is null or pre_digest ~ '^[0-9a-f]{64}$'),
  post_digest text check (post_digest is null or post_digest ~ '^[0-9a-f]{64}$'),
  trusted_editorial_rights_assertion boolean not null default false
);

create index if not exists filesystem_mutation_audit_path_time_idx
  on devotional_workspace.filesystem_mutation_audit (path, occurred_at desc);

create or replace function devotional_workspace.reject_audit_mutation()
returns trigger
language plpgsql
as $$
begin
  raise exception 'filesystem mutation audit is append-only';
end;
$$;

drop trigger if exists filesystem_mutation_audit_append_only
  on devotional_workspace.filesystem_mutation_audit;
create trigger filesystem_mutation_audit_append_only
before update or delete on devotional_workspace.filesystem_mutation_audit
for each statement execute function devotional_workspace.reject_audit_mutation();

create table if not exists devotional_workspace.workspace_readiness (
  singleton boolean primary key default true check (singleton),
  ready boolean not null default false,
  manifest_digest text,
  reason text,
  verified_at timestamptz,
  updated_at timestamptz not null default now()
