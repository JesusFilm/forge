import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const scriptDir = dirname(fileURLToPath(import.meta.url))
const appDir = join(scriptDir, "..")
const messagesDir = join(appDir, "messages")
const outputPath = join(appDir, "src/i18n/generated-ui-locales.ts")
const DEFAULT_LOCALE = "en"
const LOCALE_TAG_PATTERN = /^[a-z]{2,3}(?:-[a-z0-9]{2,8})*$/i

function normalizeBcp47Tag(tag) {
  return tag
    .split("-")
    .map((part, index) => {
      if (index === 0) return part.toLowerCase()
      if (/^[a-z]{4}$/i.test(part)) {
        return part[0]?.toUpperCase() + part.slice(1).toLowerCase()
      }
      if (/^[a-z]{2}$/i.test(part)) return part.toUpperCase()
      return part.toLowerCase()
    })
    .join("-")
}

function discoverLocales() {
  const locales = readdirSync(messagesDir)
    .filter((file) => file.endsWith(".json"))
    .map((file) => file.slice(0, -5))
    .sort((a, b) => a.localeCompare(b))

  if (!locales.includes(DEFAULT_LOCALE)) {
    throw new Error(`Missing required default catalog: ${DEFAULT_LOCALE}.json`)
  }

  for (const locale of locales) {
    if (!LOCALE_TAG_PATTERN.test(locale)) {
      throw new Error(`Invalid UI locale catalog filename: ${locale}.json`)
    }
    const normalized = normalizeBcp47Tag(locale)
    if (locale !== normalized) {
      throw new Error(
        `UI locale catalog filename must be normalized: ${locale}.json -> ${normalized}.json`,
      )
    }
  }

  return locales
}

function render(locales) {
  const localeArray = locales.map((locale) => JSON.stringify(locale)).join(", ")
  return [
    "// This file is generated by `pnpm --filter @forge/web generate:ui-locales`.",
    "// Do not edit it by hand; add or remove apps/web/messages/*.json instead.",
    "",
    `export const DEFAULT_LOCALE = ${JSON.stringify(DEFAULT_LOCALE)} as const`,
    "",
    `export const AVAILABLE_UI_LOCALES = [${localeArray}] as const`,
    "",
    "export type UiLocale = (typeof AVAILABLE_UI_LOCALES)[number]",
    "",
    "const AVAILABLE_UI_LOCALE_SET: ReadonlySet<string> = new Set(",
    "  AVAILABLE_UI_LOCALES,",
    ")",
    "",
    "export function hasUiLocale(candidate: string): candidate is UiLocale {",
    "  return AVAILABLE_UI_LOCALE_SET.has(candidate)",
    "}",
    "",
  ].join("\n")
}

function main() {
  const check = process.argv.includes("--check")
  const nextContent = render(discoverLocales())

  if (check) {
    const current = existsSync(outputPath)
      ? readFileSync(outputPath, "utf-8")
      : ""
    if (current !== nextContent) {
      const displayPath = relative(appDir, outputPath)
      console.error(
        `${displayPath} is stale. Run pnpm --filter @forge/web generate:ui-locales.`,
      )
      process.exitCode = 1
    }
    return
  }

  writeFileSync(outputPath, nextContent)
}

main()
