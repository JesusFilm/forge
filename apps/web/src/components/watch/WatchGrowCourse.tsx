type RecapRow = {
  lesson: Lesson
  mood: string
  answer: string
  commit: string
  day: string
  names: string[]
  watched: number
  stills: number
  done: boolean
}

function recapRows(
  lessonOf: (n: number) => LessonState,
  isDone: (lesson: Lesson) => boolean,
): RecapRow[] {
  return LESSONS.map((lesson) => {
    const st = lessonOf(lesson.n)
    const answer =
      lesson.questions
        .map((_, i) => st.notes[`q-${lesson.n}-${i}`] ?? "")
        .find((v) => v.trim().length > 0) ?? ""
    const [commit, day] = (
      st.notes[stepKey("forward", lesson.n, "differently")] ?? ""
    ).split("|")
    return {
      lesson,
      mood: st.notes[stepKey("back", lesson.n, "how")] ?? "",
      answer: answer.trim(),
      commit: (commit ?? "").trim(),
      day: day ?? "",
      names: (st.notes[stepKey("back", lesson.n, "carrying")] ?? "")
        .split(",")
        .map((x) => x.trim())
        .filter(Boolean),
      watched: st.watched,
      stills: ["quiet", "retell", "thanks", "lands", "for-them"].filter(
        (id) =>
          st.notes[stepKey("back", lesson.n, id)] === "done" ||
          st.notes[stepKey("forward", lesson.n, id)] === "done",
      ).length,
      done: isDone(lesson),
    }
  })
}

function Recap({
  lessonOf,
  isDone,
  onClose,
}: {
  lessonOf: (n: number) => LessonState
  isDone: (lesson: Lesson) => boolean
  onClose: () => void
}) {
  const [copied, setCopied] = useState(false)
  const rows = recapRows(lessonOf, isDone)
  const written = rows.filter((r) => r.answer || r.commit || r.names.length > 0)
  const names = Array.from(new Set(rows.flatMap((r) => r.names)))
  const watched = rows.filter((r) => r.watched > 0).length
  const stills = rows.reduce((n, r) => n + r.stills, 0)
  const commitments = rows.filter((r) => r.commit).length

  const asText = [
    "Beginning With Jesus — what I have written so far",
    "",
    ...written.flatMap((r) => [
      `${r.lesson.n}. ${r.lesson.title}`,
      r.mood ? `   The week: ${r.mood}` : "",
      r.answer ? `   I wrote: ${r.answer}` : "",
      r.commit
        ? `   I said I would: ${r.commit}${r.day ? ` by ${r.day}` : ""}`
        : "",
      r.names.length ? `   I prayed for: ${r.names.join(", ")}` : "",
      "",
    ]),
  ]
    .filter((l) => l !== "")
    .join("\n")

  return (
    <div
      data-testid="watch-grow-course-recap"
      className={cn("mt-6 min-w-0 overflow-hidden rounded-2xl", SHEET)}
    >
      <div className="flex min-w-0 flex-wrap items-start justify-between gap-4 px-5 pt-6 sm:px-7">
        <div className="min-w-0">
          <p className="text-[11px] font-bold tracking-[0.18em] text-brand-red uppercase">
            In your own words
          </p>
          <h4 className="mt-2 text-[26px] leading-tight font-bold text-balance">
            What you have written
          </h4>
        </div>
        <button
          type="button"
          onClick={onClose}
          aria-label="Close"
          className="grid size-9 shrink-0 cursor-pointer place-items-center rounded-full border border-stone-900/15 transition-colors hover:border-stone-900/50 focus-visible:outline-none"
        >
          <X aria-hidden className="size-4" />
        </button>
      </div>

      <div className="mt-5 grid min-w-0 gap-px bg-stone-900/10 sm:grid-cols-4">
        {[
          {
            n: watched,
            label: watched === 1 ? "story watched" : "stories watched",
          },
          { n: written.length, label: "sessions you wrote in" },
          {
            n: commitments,
            label:
              commitments === 1
                ? "thing you said you would do"
                : "things you said you would do",
          },
          {
            n: names.length,
            label:
              names.length === 1 ? "person you carried" : "people you carried",
          },
        ].map((t) => (
          <div key={t.label} className="min-w-0 bg-[#efece4] px-5 py-4">
            <p className="text-[28px] leading-none font-bold tabular-nums">
              {t.n}
            </p>
            <p className="mt-1.5 text-[12px] leading-snug text-stone-900/50">
              {t.label}
            </p>
          </div>
        ))}
      </div>

      <div className="min-w-0 px-5 py-6 sm:px-7">
        {written.length === 0 ? (
          <p className="text-[15px] text-stone-900/55">
            Nothing yet. Write one answer and it will be here.
          </p>
        ) : (
          <ol className="grid min-w-0 gap-5">
            {written.map((r) => (
              <li
                key={r.lesson.n}
                data-testid="watch-grow-course-recap-row"
                className="min-w-0 border-l-2 border-brand-red/40 pl-4"
              >
                <p className="text-[12px] font-bold tracking-[0.12em] text-stone-900/40 uppercase">
                  {r.lesson.n} · {r.lesson.segment}
                  {r.mood ? ` · the week felt ${r.mood.toLowerCase()}` : ""}
                </p>
                {r.answer ? (
                  <p className="mt-1.5 max-w-[62ch] text-[17px] leading-snug font-medium text-balance">
                    &ldquo;{r.answer}&rdquo;
                  </p>
                ) : null}
                {r.commit ? (
                  <p className="mt-1.5 text-[14px] text-stone-900/65">
                    You said you would {r.commit}
                    {r.day ? ` by ${r.day}` : ""}.
                  </p>
                ) : null}
                {r.names.length ? (
                  <p className="mt-1 text-[14px] text-stone-900/45">
                    You carried {r.names.join(", ")}.
                  </p>
                ) : null}
              </li>
            ))}
          </ol>
        )}

        <div className="mt-6 flex min-w-0 flex-wrap items-center gap-3">
          <button
            type="button"
            data-testid="watch-grow-course-recap-copy"
            disabled={written.length === 0}
            onClick={() => {
              void navigator.clipboard?.writeText(asText)
              setCopied(true)
              window.setTimeout(() => setCopied(false), 1800)
            }}
            className="inline-flex h-11 cursor-pointer items-center gap-2 rounded-full bg-stone-900 px-5 text-[13px] font-semibold text-[#efece4] transition-opacity disabled:cursor-default disabled:opacity-30 focus-visible:outline-none"
          >
            {copied ? (
              <Check aria-hidden className="size-4" />
            ) : (
              <Copy aria-hidden className="size-4" />
            )}
            {copied ? "Copied" : "Copy it out"}
          </button>
          <p className="min-w-0 text-[12px] text-stone-900/40">
            {stills > 0
              ? `You also stopped and stayed quiet ${stills} ${stills === 1 ? "time" : "times"}.`
              : "Nothing here leaves this tab."}
          </p>
        </div>
      </div>
    </div>
  )
}

