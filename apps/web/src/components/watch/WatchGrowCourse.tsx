const RETELL_SECONDS = 60

function RetellBlock({
  lesson,
  mode,
  state,
  patch,
}: {
  lesson: Lesson
  mode: Mode
  state: LessonState
  patch: (p: Partial<PageLesson>) => void
}) {
  const [left, setLeft] = useState<number | null>(null)

  useEffect(() => {
    if (left === null) return
    if (left <= 0) {
      setLeft(null)
      patch({ retold: true })
      return
    }
    const t = window.setTimeout(() => setLeft(left - 1), 1000)
    return () => window.clearTimeout(t)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [left])

  const running = left !== null
  const pct = running ? 1 - (left ?? 0) / RETELL_SECONDS : 0

  return (
    <div className="min-w-0 rounded-2xl border border-stone-900/12 p-5">
      <div className="flex min-w-0 flex-col items-start gap-4 sm:flex-row sm:items-center sm:gap-5">
        <div className="relative grid size-16 shrink-0 place-items-center">
          <svg
            viewBox="0 0 48 48"
            aria-hidden
            className="absolute size-16 -rotate-90"
          >
            <circle
              cx="24"
              cy="24"
              r="21"
              fill="none"
              strokeWidth="3"
              className="stroke-stone-900/12"
            />
            <circle
              cx="24"
              cy="24"
              r="21"
              fill="none"
              strokeWidth="3"
              stroke={BRAND_RED}
              strokeLinecap="round"
              strokeDasharray={2 * Math.PI * 21}
              strokeDashoffset={2 * Math.PI * 21 * (1 - pct)}
            />
          </svg>
          {running ? (
            <span className="text-[15px] font-bold tabular-nums">{left}</span>
          ) : state.retold ? (
            <Check aria-hidden className="size-6 text-brand-red" />
          ) : (
            <Mic aria-hidden className="size-6 text-stone-900/40" />
          )}
        </div>
        <div className="w-full min-w-0 sm:flex-1">
          <p className="text-[15px] font-semibold">
            {mode === "solo"
              ? "Now tell it back, out loud"
              : "Ask someone to tell the story back"}
          </p>
          <p className="mt-1 max-w-[52ch] text-[13px] leading-relaxed text-stone-900/55">
            {mode === "solo" ? LESSON_STEPS[1].solo : LESSON_STEPS[1].group}{" "}
            {mode === "solo"
              ? "Saying it is what makes it yours — and it is how you will tell someone else."
              : "Then let the others fill in the gaps."}
          </p>
        </div>
        <button
          type="button"
          data-testid="watch-grow-course-retell"
          onClick={() => (running ? setLeft(null) : setLeft(RETELL_SECONDS))}
          className={cn(
            "inline-flex h-10 w-full shrink-0 cursor-pointer items-center justify-center gap-2 rounded-full px-4 text-[13px] font-semibold transition-colors focus-visible:outline-none sm:w-auto",
            running
              ? "bg-stone-900/10 text-stone-900 hover:bg-stone-900/20"
              : "bg-stone-900 text-[#efece4] hover:bg-stone-800",
          )}
        >
          {running
            ? "Stop"
            : state.retold
              ? "Tell it again"
              : "Give me a minute"}
        </button>
      </div>
      <p className="sr-only">Lesson {lesson.n} retell timer</p>
    </div>
  )
}

function QuestionDeck({
  lesson,
  state,
  setNote,
}: {
  lesson: Lesson
  state: LessonState
  setNote: (key: string, value: string) => void
}) {
  const [at, setAt] = useState(0)
  const total = lesson.questions.length
  const key = `q-${lesson.n}-${at}`
  const answered = lesson.questions.filter(
    (_, i) => (state.notes[`q-${lesson.n}-${i}`] ?? "").trim().length > 0,
  ).length

  return (
    <div className="min-w-0">
      <div className="flex min-w-0 flex-wrap items-baseline justify-between gap-x-4 gap-y-1">
        <SectionTitle>Discussion</SectionTitle>
        <p className="text-[12px] text-stone-900/45">
          {total} questions · {answered} answered · it is not necessary to
          complete all of them
        </p>
      </div>

      <div className="mt-3 min-w-0 rounded-2xl bg-stone-900 p-5 text-[#efece4] sm:p-6">
        <p className="text-[11px] font-bold tracking-[0.18em] text-[#efece4]/45 uppercase">
          Question {at + 1} of {total}
        </p>
        <p
          data-testid="watch-grow-course-question"
          className="mt-3 max-w-[46ch] text-[20px] leading-snug font-semibold text-balance sm:text-[24px]"
        >
          {lesson.questions[at]}
        </p>

        <NoteField
          key={`${key}|${state.notes[key] ?? ""}`}
          dark
          value={state.notes[key] ?? ""}
          placeholder="Your answer — kept in this tab only."
          rows={3}
          onCommit={(v) => setNote(key, v)}
        />

        <div className="mt-5 flex min-w-0 flex-wrap items-center gap-3">
          <button
            type="button"
            onClick={() => setAt((v) => Math.max(0, v - 1))}
            disabled={at === 0}
            className="inline-flex size-9 cursor-pointer items-center justify-center rounded-full border border-[#efece4]/20 transition-colors hover:border-[#efece4] disabled:cursor-default disabled:opacity-25 focus-visible:outline-none"
            aria-label="Previous question"
          >
            <ArrowLeft aria-hidden className="size-4" />
          </button>
          <button
            type="button"
            data-testid="watch-grow-course-question-next"
            onClick={() => setAt((v) => Math.min(total - 1, v + 1))}
            disabled={at === total - 1}
            className="inline-flex size-9 cursor-pointer items-center justify-center rounded-full border border-[#efece4]/20 transition-colors hover:border-[#efece4] disabled:cursor-default disabled:opacity-25 focus-visible:outline-none"
            aria-label="Next question"
          >
            <ArrowRight aria-hidden className="size-4" />
          </button>
          <div className="flex min-w-0 flex-wrap items-center gap-1.5">
            {lesson.questions.map((q, i) => (
              <button
                key={q}
                type="button"
                onClick={() => setAt(i)}
                aria-label={`Question ${i + 1}`}
                className={cn(
                  "h-1.5 cursor-pointer rounded-full transition-all",
                  i === at
                    ? "w-6 bg-brand-red"
                    : (state.notes[`q-${lesson.n}-${i}`] ?? "").trim()
                      ? "w-3 bg-[#efece4]/70"
                      : "w-3 bg-[#efece4]/25 hover:bg-[#efece4]/50",
                )}
              />
            ))}
          </div>
        </div>
      </div>
    </div>
  )
}

