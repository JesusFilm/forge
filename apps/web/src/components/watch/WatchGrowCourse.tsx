/**
 * The guide prints these as bullets. A bullet with a tickbox is a form, and a
 * form is the thing you fill in on autopilot — so each line here is its own
 * small act: a word for your week, a name you carry, a minute you sit through.
 * A step is done when it has an answer; nothing is ticked by hand.
 */
function PromptSteps({
  groups,
  third,
  lesson,
  mode,
  state,
  setNote,
}: {
  groups: PromptGroup[]
  third: MovementId
  lesson: Lesson
  mode: Mode
  state: LessonState
  setNote: (key: string, value: string) => void
}) {
  const all = groups.flatMap((g) => g.items)
  const done = all.filter(
    (i) =>
      (state.notes[stepKey(third, lesson.n, i.id)] ?? "").trim().length > 0,
  ).length

  const numberOf = new Map(all.map((i, idx) => [i.id, idx + 1]))

  return (
    <div className="min-w-0">
      <div className="flex min-w-0 flex-wrap items-baseline justify-between gap-x-4 gap-y-1">
        <SectionTitle>{movementOf(third).name}</SectionTitle>
        <p className="text-[12px] tabular-nums text-stone-900/45">
          {done} of {all.length} done
        </p>
      </div>

      <div className="mt-3 grid min-w-0 gap-3">
        {groups.map((g) => (
          <div key={g.title} className="grid min-w-0 gap-3">
            <p className="mt-2 text-[12px] font-bold tracking-[0.14em] text-stone-900/35 uppercase">
              {g.title}
            </p>
            {g.items.map((item) => {
              const key = stepKey(third, lesson.n, item.id)
              return (
                <StepCard
                  key={item.id}
                  n={numberOf.get(item.id) ?? 0}
                  line={mode === "solo" ? item.solo : item.group}
                  value={state.notes[key] ?? ""}
                >
                  <StepControl
                    ui={item.ui}
                    value={state.notes[key] ?? ""}
                    onChange={(v) => setNote(key, v)}
                    extra={state.notes[`${key}:more`] ?? ""}
                    onExtra={(v) => setNote(`${key}:more`, v)}
                    carrying={
                      state.notes[stepKey("back", lesson.n, "carrying")] ?? ""
                    }
                  />
                </StepCard>
              )
            })}
          </div>
        ))}
      </div>
    </div>
  )
}

