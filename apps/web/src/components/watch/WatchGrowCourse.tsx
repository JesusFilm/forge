/** The original's note keys, kept so the screens below read as written. */
function stepKey(third: MovementId, lesson: number, id: string): string {
  return `p:${third}:${lesson}:${id}`
}

/** Original note key → the draft step id both views share. */
function noteStep(key: string): string {
  const more = key.endsWith(":more")
  const base = more ? key.slice(0, -":more".length) : key
  const step = base.match(/^p:(back|up|forward):\d+:(.+)$/)
  const question = base.match(/^q-\d+-(\d+)$/)
  const id = step
    ? stepDraftId(step[1] as MovementId, step[2]!)
    : question
      ? questionDraftId(Number(question[1]))
      : base
  return more ? `${id}:more` : id
}

/** Re-render on any draft change; drafts are read straight from the store. */
function useDraftReader(store: WatchLearningDraftStore) {
  const [, changed] = useReducer((n: number) => n + 1, 0)
  useEffect(() => store.subscribe(changed), [store])
  return (lesson: Lesson, key: string) =>
    store.get(draftKey(lesson, noteStep(key)))
}

function notesOf(
  lesson: Lesson,
  read: (lesson: Lesson, key: string) => string,
): Record<string, string> {
  const notes: Record<string, string> = {}
  const add = (key: string) => {
    const value = read(lesson, key)
    if (value) notes[key] = value
  }
  for (const [third, groups] of [
    ["back", LOOKING_BACK],
    ["forward", LOOKING_FORWARD],
  ] as const) {
    for (const group of groups)
      for (const item of group.items) {
        add(stepKey(third, lesson.n, item.id))
        add(`${stepKey(third, lesson.n, item.id)}:more`)
      }
  }
  lesson.questions.forEach((_, i) => add(`q-${lesson.n}-${i}`))
  return notes
}

/* ---------------------------------------------------------------------------
   The guide's three-thirds mark, redrawn. Three annular sectors around a
   centre, each with a triangle pointing its own way: back, up, forward.
--------------------------------------------------------------------------- */

const SECTOR_CENTRE: Record<MovementId, number> = {
  up: -90,
  forward: 30,
  back: 150,
}

function polar(r: number, deg: number): [number, number] {
  const rad = (deg * Math.PI) / 180
  return [24 + r * Math.cos(rad), 24 + r * Math.sin(rad)]
}

function sectorPath(centre: number, span: number, r0: number, r1: number) {
  const a0 = centre - span / 2
  const a1 = centre + span / 2
  const [x0, y0] = polar(r1, a0)
  const [x1, y1] = polar(r1, a1)
  const [x2, y2] = polar(r0, a1)
  const [x3, y3] = polar(r0, a0)
  return `M${x0} ${y0} A${r1} ${r1} 0 0 1 ${x1} ${y1} L${x2} ${y2} A${r0} ${r0} 0 0 0 ${x3} ${y3} Z`
}

function trianglePath(centre: number, r: number, size: number) {
  const [tx, ty] = polar(r + size, centre)
  const [lx, ly] = polar(r, centre - 11)
  const [rx, ry] = polar(r, centre + 11)
  return `M${tx} ${ty} L${lx} ${ly} L${rx} ${ry} Z`
}

/**
 * In the printed guide the triangles are cut out of each petal, so they read as
 * the paper showing through. `bg` is that paper — pass whatever the mark sits on.
 */
function ThirdsMark({
  done,
  active,
  tone = "dark",
  bg = "#0c0a09",
  className,
}: {
  done: MovementId[]
  active?: MovementId | null
  tone?: "dark" | "light"
  bg?: string
  className?: string
}) {
  return (
    <svg
      viewBox="0 0 48 48"
      aria-hidden
      className={cn("shrink-0", className)}
      fill="none"
    >
      {MOVEMENTS.map(({ id }) => {
        const isDone = done.includes(id)
        const isActive = active === id
        const fill = isActive
          ? BRAND_RED
          : isDone
            ? tone === "dark"
              ? "rgba(255,255,255,0.92)"
              : "rgba(28,25,23,0.85)"
            : tone === "dark"
              ? "rgba(255,255,255,0.28)"
              : "rgba(28,25,23,0.2)"
        const centre = SECTOR_CENTRE[id]
        return (
          <g key={id}>
            <path d={sectorPath(centre, 98, 10.5, 21)} fill={fill} />
            <path d={trianglePath(centre, 13.4, 4.4)} fill={bg} />
          </g>
        )
      })}
    </svg>
  )
}

