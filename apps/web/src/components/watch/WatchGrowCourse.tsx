function StillControl({
  seconds,
  verb,
  done,
  onDone,
}: {
  seconds: number
  verb: string
  done: boolean
  onDone: () => void
}) {
  const [left, setLeft] = useState<number | null>(null)

  useEffect(() => {
    if (left === null) return
    if (left <= 0) {
      setLeft(null)
      onDone()
      return
    }
    const t = window.setTimeout(() => setLeft(left - 1), 1000)
    return () => window.clearTimeout(t)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [left])

  const running = left !== null
  const pct = running ? 1 - (left ?? 0) / seconds : done ? 1 : 0

  return (
    <div className="flex min-w-0 flex-wrap items-center gap-4">
      <RingTimer pct={pct} size="sm">
        {running ? (
          <span className="text-[13px] font-bold tabular-nums">{left}</span>
        ) : done ? (
          <Check aria-hidden className="size-5 text-brand-red" />
        ) : (
          <Timer aria-hidden className="size-5 text-stone-900/35" />
        )}
      </RingTimer>
      <button
        type="button"
        data-testid="watch-grow-course-still"
        onClick={() => (running ? setLeft(null) : setLeft(seconds))}
        className={cn(
          "inline-flex h-11 cursor-pointer items-center gap-2 rounded-full px-5 text-[13px] font-semibold transition-colors focus-visible:outline-none",
          running
            ? "bg-stone-900/10 text-stone-900 hover:bg-stone-900/20"
            : "bg-stone-900 text-[#efece4] hover:bg-stone-800",
        )}
      >
        {running ? "Stop" : done ? "Again" : verb}
      </button>
      {!running && !done ? (
        <span className="text-[13px] text-stone-900/40">
          {seconds < 60
            ? `${seconds} seconds`
            : seconds === 60
              ? "one minute"
              : `${seconds / 60} minutes`}
        </span>
      ) : null}
    </div>
  )
}

function RingTimer({
  pct,
  size = "lg",
  children,
}: {
  pct: number
  size?: "sm" | "lg"
  children: ReactNode
}) {
  const r = 21
  const c = 2 * Math.PI * r
  return (
    <div
      className={cn(
        "relative grid shrink-0 place-items-center",
        size === "lg" ? "size-16" : "size-12",
      )}
    >
      <svg
        viewBox="0 0 48 48"
        aria-hidden
        className={cn(
          "absolute -rotate-90",
          size === "lg" ? "size-16" : "size-12",
        )}
      >
        <circle
          cx="24"
          cy="24"
          r={r}
          fill="none"
          strokeWidth="3"
          className="stroke-stone-900/12"
        />
        <circle
          cx="24"
          cy="24"
          r={r}
          fill="none"
          strokeWidth="3"
          stroke={BRAND_RED}
          strokeLinecap="round"
          strokeDasharray={c}
          strokeDashoffset={c * (1 - pct)}
        />
      </svg>
      {children}
    </div>
  )
}

/** One line, committed on blur. */
function LineField({
  value,
  placeholder,
  onCommit,
}: {
  value: string
  placeholder: string
  onCommit: (v: string) => void
}) {
  const [draft, setDraft] = useState(value)
  return (
    <input
      value={draft}
      placeholder={placeholder}
      data-testid="watch-grow-course-line"
      onChange={(e) => setDraft(e.target.value)}
      onBlur={() => {
        if (draft !== value) onCommit(draft)
      }}
      className="mt-3 h-11 w-full min-w-0 rounded-xl border border-stone-900/15 bg-white/60 px-4 text-[14px] transition-colors placeholder:text-stone-900/35 focus:border-stone-900/50 focus:outline-none"
    />
  )
}

