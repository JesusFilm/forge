describe("Beginning With Jesus curriculum", () => {
  it("matches every accepted lesson, completable step and resume card in order", () => {
    expect(BWJ.courseId).toBe("beginning-with-jesus")
    expect(BWJ.contentVersion).toBe("2026-10-17-v1")
    expect(MOVEMENTS.map((m) => m.id)).toEqual(["back", "up", "forward"])
    expect(
      LESSONS.map((lesson) => ({
        lessonId: lesson.id,
        slug: lesson.slug,
        stepIds: lessonCards(lesson)
          .filter((card) => card.completable)
          .map((card) => card.id),
        cardIds: lessonCards(lesson).map((card) => card.id),
      })),
    ).toEqual(expected)
    expect(lessonCards(LESSONS[0]!)).toHaveLength(26)
  })

  it("keeps nine source-backed lessons, benefit first and complete guide teaching", () => {
    expect(LESSONS).toHaveLength(9)
    for (const lesson of LESSONS) {
      expect(lesson.why.promise.length).toBeGreaterThan(10)
      expect(lesson.why.payoff.length).toBeGreaterThan(20)
      expect(lesson.sourcePage).toBe(lesson.n + 9)
      expect(lesson.intro).toBeTruthy()
      expect(lesson.questions.length).toBeGreaterThanOrEqual(4)
      expect(lesson.conclusion).toBeTruthy()
      expect(lessonCards(lesson)[0]?.body).toContain(lesson.why.payoff)
      expect(chapterHref(lesson.slug)).toBe(`/jesus.html/${lesson.slug}.html`)
      expect(lesson).not.toHaveProperty("playbackId")
      expect(lesson).not.toHaveProperty("seconds")
    }
    expect(BWJ.copyright).toBe(
      "Beginning With Jesus v2 © 2023 Jesus Film Project",
    )
    expect(BWJ.pdf).toBe(
      "https://www.jesusfilm.org/wp-content/uploads/2026/03/Beginning-With-Jesus.pdf",
    )
    expect(LESSONS[0]?.questions[3]).toBe(
      "Why is it important that you be sure of your salvation?",
    )
    expect(LESSONS[8]?.leaderNote).toContain("continue to follow Jesus")
  })
})
