#!/usr/bin/env node
// Writes src/i18n/{catalogs,pluralData}.generated.ts from messages/ (KTD1,
// KTD5). Run `node scripts/i18n/generate-catalog-index.mjs [--check]`. Not a
// package.json script: a new script entry moves the Expo fingerprint (KTD4).

import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"
import path from "node:path"
import fs from "node:fs"

const HERE = path.dirname(fileURLToPath(import.meta.url))
const MOBILE = path.resolve(HERE, "../..")
const REPO = path.resolve(MOBILE, "../..")

const CATALOGS_FILE = "catalogs.generated.ts"
const PLURAL_DATA_FILE = "pluralData.generated.ts"
const DEFAULT_TAG = "en"
const PLURAL_DATA_PACKAGE = "@formatjs/intl-pluralrules"

// language[-Script][-REGION], spelled as apps/web/messages spells its files.
const CATALOG_TAG = /^[a-z]{2,3}(?:-[A-Z][a-z]{3})?(?:-(?:[A-Z]{2}|\d{3}))?$/

class CatalogIndexError extends Error {}

function parseArgs(argv) {
  const options = {
    check: false,
    messagesDir: path.join(MOBILE, "messages"),
    outDir: path.join(MOBILE, "src", "i18n"),
  }
  for (const arg of argv) {
    if (arg === "--check") options.check = true
    else if (arg.startsWith("--messages-dir=")) {
      options.messagesDir = path.resolve(arg.slice("--messages-dir=".length))
    } else if (arg.startsWith("--out-dir=")) {
      options.outDir = path.resolve(arg.slice("--out-dir=".length))
    } else {
      throw new CatalogIndexError(`Unknown argument: ${arg}`)
    }
  }
  return options
}

function readCatalogTags(messagesDir) {
  const files = fs
    .readdirSync(messagesDir)
    .filter((name) => name.endsWith(".json"))
    .sort()
  const tags = []
  for (const file of files) {
    const tag = file.slice(0, -".json".length)
    if (!CATALOG_TAG.test(tag)) {
      throw new CatalogIndexError(
        `${file} is not named as a catalog tag (language[-Script][-REGION]).`,
      )
    }
    try {
      JSON.parse(fs.readFileSync(path.join(messagesDir, file), "utf8"))
    } catch (error) {
      throw new CatalogIndexError(`${file} is not valid JSON: ${error.message}`)
    }
    tags.push(tag)
  }
  if (!tags.includes(DEFAULT_TAG)) {
    throw new CatalogIndexError(
      `${path.join(messagesDir, `${DEFAULT_TAG}.json`)} is missing; English is the fallback catalog.`,
    )
  }
  return tags
}

function readPluralDataTags() {
  const entry = createRequire(path.join(MOBILE, "package.json")).resolve(
    PLURAL_DATA_PACKAGE,
  )
  const dataDir = path.join(path.dirname(entry), "locale-data")
  return new Set(
    fs
      .readdirSync(dataDir)
      .filter((name) => name.endsWith(".js"))
      .map((name) => name.slice(0, -".js".length)),
  )
}

// The exact data tag the polyfill has for a catalog tag: the tag, the tag
// without its script, then the language. No CLDR data means English (KTD1).
function pluralDataTagFor(tag, dataTags) {
  const [language, ...rest] = tag.split("-")
  const candidates = [tag]
  if (rest[0]?.length === 4) {
    candidates.push([language, ...rest.slice(1)].join("-"))
  }
  candidates.push(language)
  return candidates.find((candidate) => dataTags.has(candidate)) ?? DEFAULT_TAG
}

function objectKey(tag) {
  return /^[A-Za-z_$][\w$]*$/.test(tag) ? tag : JSON.stringify(tag)
}

const HEADER = [
  "// Generated by scripts/i18n/generate-catalog-index.mjs. Do not edit.",
  "// Run `node scripts/i18n/generate-catalog-index.mjs` after a catalog change.",
  "/* eslint-disable @typescript-eslint/no-require-imports */",
].join("\n")

function catalogsSource(tags, messagesImportPath) {
  const loaders = tags
    .map(
      (tag) =>
        `  ${objectKey(tag)}: () => require(${JSON.stringify(`${messagesImportPath}/${tag}.json`)}),`,
    )
    .join("\n")
  return `${HEADER}

export const CATALOG_TAGS = ${JSON.stringify(tags)} as const

export type CatalogTag = (typeof CATALOG_TAGS)[number]

// A thunk keeps its catalog in the bundle but off the heap until it runs (R8).
export const CATALOG_LOADERS: Record<CatalogTag, () => object> = {
${loaders}
}
`
}

function pluralDataSource(tags, dataTags) {
  const byCatalog = tags.map((tag) => [tag, pluralDataTagFor(tag, dataTags)])
  const loadedTags = [
    ...new Set(byCatalog.map(([, dataTag]) => dataTag)),
  ].sort()
  const mapping = byCatalog
    .map(([tag, dataTag]) => `  ${objectKey(tag)}: ${JSON.stringify(dataTag)},`)
    .join("\n")
  const loaders = loadedTags
    .map(
      (dataTag) =>
        `  ${objectKey(dataTag)}: () => require(${JSON.stringify(`${PLURAL_DATA_PACKAGE}/locale-data/${dataTag}.js`)}),`,
    )
    .join("\n")
  return `${HEADER}

import type { CatalogTag } from "./catalogs.generated"

export const PLURAL_DATA_TAGS = ${JSON.stringify(loadedTags)} as const

export type PluralDataTag = (typeof PLURAL_DATA_TAGS)[number]

// The exact CLDR data tag each catalog formats plurals under (KTD1).
export const PLURAL_DATA_TAG: Record<CatalogTag, PluralDataTag> = {
${mapping}
}

export const PLURAL_DATA_LOADERS: Record<PluralDataTag, () => void> = {
${loaders}
}
`
}

async function format(source) {
  const prettier = createRequire(path.join(REPO, "package.json"))("prettier")
  // Resolve the config for the real output path, so a test out dir formats
  // exactly as the committed files do.
  const config = await prettier.resolveConfig(
    path.join(MOBILE, "src", "i18n", CATALOGS_FILE),
  )
  return prettier.format(source, { ...config, parser: "typescript" })
}

async function main() {
  const options = parseArgs(process.argv.slice(2))
  const tags = readCatalogTags(options.messagesDir)
  const messagesImportPath = path
    .relative(options.outDir, options.messagesDir)
    .split(path.sep)
    .join("/")
  const outputs = {
    [CATALOGS_FILE]: await format(catalogsSource(tags, messagesImportPath)),
    [PLURAL_DATA_FILE]: await format(
      pluralDataSource(tags, readPluralDataTags()),
    ),
  }

  if (options.check) {
    const drifted = Object.entries(outputs)
      .filter(([file, expected]) => {
        const target = path.join(options.outDir, file)
        return (
          !fs.existsSync(target) || fs.readFileSync(target, "utf8") !== expected
        )
      })
      .map(([file]) => file)
    if (drifted.length > 0) {
      console.error(
        `Catalog index is out of date: ${drifted.join(", ")}.\n` +
          "Run `node scripts/i18n/generate-catalog-index.mjs` in apps/mobile.",
      )
      process.exit(1)
    }
    return
  }

  for (const [file, source] of Object.entries(outputs)) {
    fs.writeFileSync(path.join(options.outDir, file), source)
  }
}

main().catch((error) => {
  console.error(
    error instanceof CatalogIndexError ? error.message : error.stack,
  )
  process.exit(1)
})
